function resolveVendorId(mfr: string, vendorMap?: Map<string, string>): string | null {
  if (!vendorMap) return null;
  const lower = mfr.toLowerCase();
  if (vendorMap.has(lower)) return vendorMap.get(lower)!;
  const known: Array<[string, string]> = [
    ['apple', 'ven-apple'],
    ['lenovo', 'ven-lenovo'],
    ['dell', 'ven-dell'],
    ['cisco', 'ven-cisco'],
    ['meraki', 'ven-cisco'],
    ['sap', 'ven-sap'],
    ['microsoft', 'ven-msft'],
    ['lectra', 'ven-lectra'],
    ['gerber', 'ven-gerber'],
    ['coats', 'ven-coats'],
    ['juki', 'ven-juki'],
    ['brother', 'ven-brother'],
  ];
  for (const [kw, id] of known) {
    if (lower.includes(kw)) return vendorMap.get(id) || id;
  }
  return null;
}

export async function seedAssets(
  prisma: PrismaClient,
  taxonomyOrCtx?: unknown,
  _users?: unknown,
  _orgResult?: unknown,
  vendorMap?: Map<string, string>,
  explicitCtx?: SeederContext,
  costCenterMap?: Map<string, string>,
): Promise<Record<string, { id: string; assetTag: string }>> {
  return runDomainSeeder(
    'AssetsSeeder',
    '💻',
    'Hardware Assets Fleet (Device Models & Physical Units)',
    async (logger) => {
      const ctx: SeederContext | undefined =
        explicitCtx ||
        (taxonomyOrCtx && typeof taxonomyOrCtx === 'object' && 'departments' in taxonomyOrCtx
          ? (taxonomyOrCtx as SeederContext)
          : undefined);

      let getDept = (code: string) => code;
      let getUser = (_email: string): string | null => null;
      const effectiveVendors = vendorMap || ctx?.vendors;

      if (ctx) {
        getDept = (code: string) =>
          ctx.departments.get(code) || ctx.departments.get('DEPT-BSL-MGMT') || code;
        getUser = (email: string) => (email ? ctx.directoryUsers.get(email) || null : null);
      } else {
        const [departments, dirUsers] = await Promise.all([
          prisma.department.findMany({ take: 200 }),
          prisma.directoryUser.findMany({ take: 100 }),
        ]);
        const deptMap = new Map<string, string>(
          departments.map((d: { code: string; id: string }) => [d.code, d.id]),
        );
        const userMap = new Map<string, string>(
          dirUsers.map((u: { email: string; id: string }) => [u.email, u.id]),
        );
        getDept = (code: string) =>
          deptMap.get(code) || deptMap.get('DEPT-BSL-MGMT') || departments[0]?.id || code;
        getUser = (email: string) => (email ? userMap.get(email) || null : null);
      }

      const getCatId = (catKey: string): string => {
        if (ctx?.assetCategories.has(catKey)) return ctx.assetCategories.get(catKey)!;
        return catKey;
      };

      const getCcId = (ccCode: string): string | null => {
        if (!costCenterMap) return null;
        return (
          costCenterMap.get(ccCode) ||
          costCenterMap.get(ccCode.toLowerCase()) ||
          costCenterMap.get(`CC-${ccCode}`) ||
          null
        );
      };

      const createdAssets: Record<string, { id: string; assetTag: string }> = {};
      const modelMap = new Map<string, { id: string; row: DeviceModelSeedDef }>();

      // ------------------------------------------------------------------------
      // Phase 1: Seed Device Models (Catalog definitions in DeviceModel)
      // ------------------------------------------------------------------------
      logger.log(`Seeding ${deviceModelRows.length} Device Models (catalog parents)...`);
      const modelRecords = await inTransactionChunks(
        prisma,
        deviceModelRows,
        50,
        async (tx, modelRow) => {
          const categoryId = getCatId(modelRow.categoryKey);
          const vendorId = resolveVendorId(modelRow.manufacturer, effectiveVendors);
          const specsJson =
            typeof modelRow.specifications === 'string'
              ? { description: modelRow.specifications, modelNumber: modelRow.model }
              : modelRow.specifications;
          const binNumber =
            modelRow.binLocation ||
            `BIN-${modelRow.categoryKey.replace('cat-', '').toUpperCase()}-01`;

          return tx.deviceModel.upsert({
            where: { modelCode: modelRow.assetCode },
            update: {
              name: modelRow.name,
              manufacturer: modelRow.manufacturer,
              categoryId,
              vendorId,
              specifications: specsJson,
              unitCost: modelRow.unitCost,
              minThreshold: modelRow.minThreshold ?? 5,
              binNumber,
            },
            create: {
              modelCode: modelRow.assetCode,
              name: modelRow.name,
              manufacturer: modelRow.manufacturer,
              categoryId,
              vendorId,
              specifications: specsJson,
              unitCost: modelRow.unitCost,
              minThreshold: modelRow.minThreshold ?? 5,
              binNumber,
            },
          });
        },
      );

      for (let i = 0; i < deviceModelRows.length; i++) {
        const mRow = deviceModelRows[i];
        const record = modelRecords[i];
        modelMap.set(mRow.assetCode, { id: record.id, row: mRow });
        createdAssets[mRow.assetCode] = {
          id: record.id,
          assetTag: mRow.assetCode,
        };
        if (ctx) {
          ctx.assets.set(mRow.assetCode, record.id);
          ctx.assets.set(record.id, record.id);
        }
      }

      // ------------------------------------------------------------------------
      // Phase 2: Seed Physical Units (Fleet Units in Asset)
      // ------------------------------------------------------------------------
      logger.log(`Seeding ${physicalUnitRows.length} Physical Units (fleet children)...`);
      const unitRecords = await inTransactionChunks(
        prisma,
        physicalUnitRows,
        50,
        async (tx, unitRow, rowIndex) => {
          const parentModel = modelMap.get(unitRow.modelCode);
          if (!parentModel) {
            throw new Error(
              `Parent device model ${unitRow.modelCode} not found for unit ${unitRow.subcode}`,
            );
          }

          const departmentId = getDept(unitRow.departmentCode);
          const assignedToId =
            unitRow.status === 'IN_USE' && unitRow.userEmail ? getUser(unitRow.userEmail) : null;
          const costCenterId =
            getCcId(unitRow.costCenterCode || parentModel.row.costCenterCode || '') ||
            (parentModel.row.costCenterCode ? getCcId(parentModel.row.costCenterCode) : null);
          const purchaseDate = new Date(unitRow.purchaseDate);
          const warrantyExpiry = new Date(unitRow.warrantyExpiry);

          const isAssigned = unitRow.status === 'IN_USE' && Boolean(assignedToId);
          const hasPendingRecord = isAssigned
            ? (unitRow.hasPendingRecord ?? rowIndex % 4 === 0)
            : false;

          return tx.asset.upsert({
            where: { subcode: unitRow.subcode },
            update: {
              deviceModelId: parentModel.id,
              assetTag: unitRow.subcode,
              serialNumber: unitRow.serialNumber,
              status: unitRow.status,
              departmentId,
              assignedToId,
              costCenterId,
              purchaseDate,
              warrantyExpiry,
              hasPendingRecord,
              notes: unitRow.notes,
            },
            create: {
              deviceModelId: parentModel.id,
              subcode: unitRow.subcode,
              assetTag: unitRow.subcode,
              serialNumber: unitRow.serialNumber,
              status: unitRow.status,
              departmentId,
              assignedToId,
              costCenterId,
              purchaseDate,
              warrantyExpiry,
              hasPendingRecord,
              notes: unitRow.notes,
            },
          });
        },
      );

      for (let i = 0; i < physicalUnitRows.length; i++) {
        const uRow = physicalUnitRows[i];
        const record = unitRecords[i];
        createdAssets[uRow.subcode] = { id: record.id, assetTag: record.assetTag || uRow.subcode };
        if (ctx) {
          ctx.assets.set(uRow.subcode, record.id);
          ctx.assets.set(record.id, record.id);
        }
      }

      // ------------------------------------------------------------------------
      // Phase 3: Seed Asset Handover Records for In-Use and Historical Assets
      // ------------------------------------------------------------------------
      logger.log('Seeding Asset Handover Records for physical units...');
      const handoverRows: Array<{
        assetId: string;
        type: HandoverRecordType;
        recipientId: string | null;
        signedDocUrl: string | null;
        isPending: boolean;
        notes: string;
        createdAt: Date;
      }> = [];

      for (let i = 0; i < physicalUnitRows.length; i++) {
        const uRow = physicalUnitRows[i];
        const record = unitRecords[i];
        const assignedToId =
          uRow.status === 'IN_USE' && uRow.userEmail ? getUser(uRow.userEmail) : null;
        const purchaseDate = new Date(uRow.purchaseDate);

        if (uRow.status === 'IN_USE' && assignedToId) {
          const isPending = Boolean(record.hasPendingRecord);
          handoverRows.push({
            assetId: record.id,
            type: HandoverRecordType.ASSIGNMENT,
            recipientId: assignedToId,
            signedDocUrl: isPending
              ? null
              : '/api/v1/assets/handover-documents/file/sample-signed-handover.pdf',
            isPending,
            notes: isPending
              ? 'Handover slip issued to custodian. Awaiting physical signature and upload.'
              : 'Signed handover documentation verified and archived in electronic repository.',
            createdAt: purchaseDate,
          });
        } else if (
          (uRow.status === 'AVAILABLE' ||
            uRow.status === 'RETIRED' ||
            uRow.status === 'MAINTENANCE') &&
          i % 5 === 0
        ) {
          const previousUser =
            getUser('tri.doan@youngonevn.com') || getUser('nam.pham@youngonevn.com');
          handoverRows.push({
            assetId: record.id,
            type: HandoverRecordType.RETURN,
            recipientId: previousUser || null,
            signedDocUrl: '/api/v1/assets/handover-documents/file/sample-signed-handover.pdf',
            isPending: false,
            notes:
              uRow.status === 'RETIRED'
                ? 'Returned for lifecycle decommissioning and certified recycling.'
                : uRow.status === 'MAINTENANCE'
                  ? 'Returned to IT hardware workshop for diagnostic analysis and repair.'
                  : 'Returned in good working condition during hardware refresh.',
            createdAt: new Date(),
          });
        }
      }

      await inTransactionChunks(prisma, handoverRows, 50, async (tx, hRow) => {
        return tx.assetHandoverRecord.create({
          data: hRow,
        });
      });
      logger.log(`✅ Seeded ${handoverRows.length} Asset Handover Records.`);

      logger.log(
        `✅ Seeded ${deviceModelRows.length} Device Models and ${physicalUnitRows.length} Physical Units across BSL & BSH.`,
      );
      return createdAssets;
    },
  );
}
